import { test, expect } from '@playwright/test'
import { campusDateTime } from '../../src/features/driving/rideForm.js'

const errors = new WeakMap()
test.beforeEach(async ({ page }) => {
  errors.set(page, [])
  page.on('pageerror', (error) => errors.get(page).push(error.message))
  await page.addInitScript(() => {
    if (!sessionStorage.getItem('driving-test-init')) {
      localStorage.setItem('darb.session.v2', 'karim')
      sessionStorage.setItem('driving-test-init', 'yes')
    }
  })
})
test.afterEach(async ({ page }) => { expect(errors.get(page)).toEqual([]) })

async function fillRide(page, extra = {}) {
  const values = { origin: 'Batroun driver test', date: campusDateTime(Date.now() + 2 * 86400000).date, time: '08:30', offeredSeats: '4', price: '3.50', ...extra }
  for (const [name, value] of Object.entries(values)) await page.locator(`[name="${name}"]`).fill(value)
}
async function headerLink(page, name) {
  const menu = page.getByRole('button', { name: 'Open menu' })
  if (await menu.isVisible() && await menu.getAttribute('aria-expanded') === 'false') await menu.click()
  await page.locator('header').getByRole('link', { name, exact: true }).click()
}
async function switchAs(page, id) {
  await page.getByLabel('Viewing as').selectOption(id ?? '')
  await expect.poll(() => page.evaluate(() => localStorage.getItem('darb.session.v2'))).toBe(id)
}
async function createRide(page, extra) {
  await page.goto('/post')
  await fillRide(page, extra)
  await page.getByRole('button', { name: 'Post the ride', exact: true }).click()
  await expect(page).toHaveURL('/my-rides/driving')
  const row = page.getByRole('listitem').filter({ hasText: 'Batroun driver test' })
  await expect(row).toBeVisible()
  return row
}

