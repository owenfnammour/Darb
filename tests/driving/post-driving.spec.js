test('departure while an open review dialog is visible closes acceptance and decline', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-11-02T07:29:00+02:00') })
  await page.goto('/my-rides/driving')
  await page.getByRole('button', { name: 'Review 2 requests' }).click()
  const panel = page.getByRole('region', { name: 'Driver request review' })
  await panel.getByRole('button', { name: "Decline Fatme Akar's request" }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.clock.fastForward(60000)
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await expect(panel.getByRole('heading', { name: 'Request review closed' })).toBeVisible()
  await expect(panel.getByRole('button', { name: /^(Accept|Decline) / })).toHaveCount(0)
  await expect(page.getByText('Departed', { exact: true })).toBeVisible()
})

