test('data-router navigation guard handles Cancel, Escape, header navigation and browser Back', async ({ page }) => {
  await page.goto('/my-rides/driving')
  await page.getByRole('link', { name: 'Post a ride', exact: true }).last().click()
  await page.getByLabel('Leaving from').fill('Unsaved draft')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Leave without posting?' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('button', { name: 'Keep editing' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await headerLink(page, 'Find a ride')
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Keep editing' }).click()
  await page.goBack()
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Discard', exact: true }).click()
  await expect(page).toHaveURL('/my-rides/driving')
})

test('existing request and queue transitions connect Driving with Ride Detail and Riding', async ({ page }) => {
  test.setTimeout(45000)
  const row = await createRide(page, { offeredSeats: '2' })
  await row.getByRole('link', { name: /Batroun driver test/ }).click()
  await switchAs(page, 'owen')
  await page.getByRole('button', { name: 'Request a seat', exact: true }).click()
  await page.getByLabel('Seats', { exact: true }).fill('2')
  await page.getByRole('button', { name: 'Send request' }).click()
  await expect(page.getByText('Request sent.', { exact: false })).toBeVisible()
  await switchAs(page, 'fatme')
  await page.getByRole('button', { name: 'Request a seat', exact: true }).click()
  await page.getByRole('button', { name: 'Send request' }).click()
  await switchAs(page, 'karim')
  await headerLink(page, 'My rides')
  await expect(page).toHaveURL('/my-rides/riding')
  await page.getByRole('link', { name: /^Driving/ }).click()
  await page.getByRole('button', { name: 'Review 2 requests' }).click()
  let panel = page.getByRole('region', { name: 'Driver request review' })
  await panel.getByRole('button', { name: "Accept Owen Nammour's request" }).click()
  await expect(panel.getByText('Full', { exact: true })).toBeVisible()
  await expect(panel.getByRole('button', { name: "Accept Fatme Akar's request" })).toHaveCount(0)
  await switchAs(page, 'fatme')
  await page.getByRole('link', { name: /^Riding/ }).click()
  await expect(page.getByRole('listitem').filter({ hasText: 'Batroun driver test' })).toContainText('First in the queue')
  await switchAs(page, 'owen')
  const mine = page.getByRole('listitem').filter({ hasText: 'Batroun driver test' })
  await expect(mine).toContainText('Accepted')
  await mine.getByRole('button', { name: 'Give up my seat' }).click()
  await mine.getByRole('button', { name: 'Give it up', exact: true }).click()
  await expect(mine).toHaveCount(0)
  await switchAs(page, 'karim')
  await page.getByRole('link', { name: /^Driving/ }).click()
  await page.getByRole('button', { name: 'Review 1 request', exact: true }).click()
  panel = page.getByRole('region', { name: 'Driver request review' })
  await panel.getByRole('button', { name: "Accept Fatme Akar's request" }).click()
  await expect(panel.getByText('1 seat left', { exact: true })).toBeVisible()
})

